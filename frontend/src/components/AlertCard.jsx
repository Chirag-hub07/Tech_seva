import { BellRing, Check } from 'lucide-react'
import { formatDate } from './RiskCard'

export default function AlertCard({ alert, onAcknowledge }) {
  const status = String(alert.status || 'pending').toLowerCase()
  const level = alert.alert_level || 'Risk'

  return (
    <article className={`alert-card ${status}`}>
      <BellRing size={20} />
      <div>
        <strong>{level} risk alert</strong>
        <p>{alert.message || 'Clinical risk notification generated by backend.'}</p>
        <small>
          Status: <em>{status}</em> · Generated {formatDate(alert.created_at)}
        </small>
      </div>
      {status === 'pending' && onAcknowledge && (
        <button onClick={() => onAcknowledge(alert.id)}>
          <Check size={16} /> Acknowledge
        </button>
      )}
    </article>
  )
}
